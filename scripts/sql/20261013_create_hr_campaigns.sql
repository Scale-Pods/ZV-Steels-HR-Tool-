-- HR Campaigns table created to store campaign metadata, status, and interview rounds
create table public.hr_campaigns (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "UserEmail" text,
  "CampaignName" text,
  "CreationDate" text,
  "CampaignStartDate" text,
  "CampaignEndDate" text,
  "NumberOfRounds" integer,
  "Description" text,
  "Location" text,
  "ExpectedAttendees" integer,
  "JDText" text,
  "Round 1" text,
  "Round 2" text,
  "Round 3" text,
  "IsActive" boolean,
  "HR Calendar Link" text,
  "Tech Calendar Link" text,
  "Manager Calendar Link" text,
  "Skills match" integer,
  "Experience relevance" integer,
  "Education/domain relevance" integer,
  "Job description alignment" integer,
  "Salary" text,
  "Joining Date" text,
  "ResumeFolder/Link" text,
  "ResumeFolderName" text,
  "Optimized" text,
  "Round1 _SD" text,
  "Round2 _SD" text,
  "Round3 _SD" text,
  "Round1 _ED" text,
  "Round2 _ED" text,
  "Round3 _ED" text,
  "Round1_time" text,
  "Round2_time" text,
  "Round3_time" text,
  "Status" text,
  "Questions" text
);

create index if not exists hr_campaigns_campaign_name_idx on public.hr_campaigns ("CampaignName");